filter_group <- function(title, content) {
  tags$details(
    class = "filter-group",
    tags$summary(title),
    tags$div(class = "filter-group-content", content)
  )
}

shinylive_download_button <- function(...) {
  button <- shiny::downloadButton(...)
  # Chromium blocks service-worker-backed Shinylive downloads when the anchor
  # has a download attribute (Chromium issue 468227).
  button$attribs$download <- NULL
  button
}

quartile_summary <- function(distribution) {
  if (is.null(distribution) || !isTRUE(distribution$ready)) {
    return(NULL)
  }

  labels <- c(
    "25th percentile (small)",
    "50th percentile (medium)",
    "75th percentile (large)"
  )
  tags$div(
    class = "quartile-summary",
    Map(function(label, value) {
      tags$div(
        class = "quartile-stat",
        tags$span(class = "quartile-label", label),
        tags$strong(class = "quartile-value", sprintf("%.2f", value))
      )
    }, labels, distribution$quartiles)
  )
}

r_assignment <- function(name, value) {
  value_text <- capture.output(dput(value))
  value_text[1] <- paste0(name, " <- ", value_text[1])
  value_text
}

build_reproduction_script <- function(filters, between_metric = "r") {
  configuration <- c(
    r_assignment("search_terms", filters$keyword),
    r_assignment("selected_fields", filters$fields),
    r_assignment("selected_conversion_bases", filters$conversion_bases),
    r_assignment("selected_preregistration", filters$preregistration),
    r_assignment("selected_year_range", filters$year_range),
    r_assignment("selected_journals", filters$journals),
    r_assignment("selected_between_metric", between_metric)
  )
  calculation_code <- readLines(
    file.path(app_directory, "R", "effect_distribution.R"),
    warn = FALSE
  )

  c(
    "# Reproduce an Empirical effect size distibution explorer result",
    "# Generated by the Shiny app. Requires base R only.",
    "",
    configuration,
    "",
    calculation_code,
    "",
    "effects <- read.csv(",
    "  \"effects.csv\",",
    "  stringsAsFactors = FALSE,",
    "  check.names = FALSE,",
    "  na.strings = c(\"\", \"NA\")",
    ")",
    "",
    "filtered_effects <- filter_effects(",
    "  effects,",
    "  keyword = search_terms,",
    "  fields = selected_fields,",
    "  conversion_bases = selected_conversion_bases,",
    "  preregistration = selected_preregistration,",
    "  year_range = selected_year_range,",
    "  journals = selected_journals",
    ")",
    "",
    "between_specification <- between_metric_spec(selected_between_metric)",
    "between <- transform_between_distribution(",
    "  prepare_effect_distribution(filtered_effects, \"between\"),",
    "  selected_between_metric",
    ")",
    "within <- prepare_effect_distribution(filtered_effects, \"within\")",
    "",
    "estimate_rows <- function(distribution, design, metric) {",
    "  estimates <- if (isTRUE(distribution$ready)) distribution$quartiles else rep(NA_real_, 3)",
    "  data.frame(",
    "    design = design,",
    "    metric = metric,",
    "    percentile = c(25, 50, 75),",
    "    magnitude = c(\"small\", \"medium\", \"large\"),",
    "    estimate = estimates,",
    "    n_articles = if (isTRUE(distribution$ready)) distribution$studies else NA_integer_,",
    "    k_effects = distribution$usable_effects",
    "  )",
    "}",
    "",
    "quartile_estimates <- rbind(",
    "  estimate_rows(between, \"Between-subjects\", between_specification$label),",
    "  estimate_rows(within, \"Within-subjects\", \"bias-corrected dz\")",
    ")",
    "write.csv(quartile_estimates, \"quartile_estimates.csv\", row.names = FALSE)",
    "print(quartile_estimates)",
    "",
    "grDevices::pdf(\"weighted_histograms.pdf\", width = 11, height = 5.5)",
    "old_par <- graphics::par(mfrow = c(1, 2))",
    "draw_effect_histogram(between, \"#2f6fa6\", between_specification$x_label)",
    "draw_effect_histogram(within, \"#6a93b8\", \"Effect size (bias-corrected dz)\")",
    "graphics::par(old_par)",
    "grDevices::dev.off()",
    "",
    "cat(\"\\nMatching effects:\", nrow(filtered_effects), \"\\n\")",
    "cat(\"Created quartile_estimates.csv and weighted_histograms.pdf\\n\")"
  )
}

write_reproduction_package <- function(result, file) {
  package_directory <- tempfile("effect-reproduction-")
  dir.create(package_directory)
  on.exit(unlink(package_directory, recursive = TRUE, force = TRUE), add = TRUE)

  write.csv(
    effects,
    file.path(package_directory, "effects.csv"),
    row.names = FALSE,
    na = ""
  )
  writeLines(
    build_reproduction_script(
      result$filters,
      if (is.null(result$between_metric)) "r" else result$between_metric
    ),
    file.path(package_directory, "reproduce.R"),
    useBytes = TRUE
  )
  writeLines(
    c(
      "Empirical effect size distibution explorer reproduction package",
      "",
      "Contents:",
      "- effects.csv: complete application dataset",
      "- reproduce.R: active filters and all code needed to reproduce the result",
      "",
      "Place both files in the same directory, open R there, and run:",
      "  source(\"reproduce.R\")",
      "",
      "The script writes quartile_estimates.csv and weighted_histograms.pdf.",
      "It uses base R only and does not calculate confidence intervals."
    ),
    file.path(package_directory, "README.txt")
  )

  archive_file <- file.path(
    normalizePath(dirname(file), mustWork = TRUE),
    basename(file)
  )
  old_directory <- setwd(package_directory)
  on.exit(setwd(old_directory), add = TRUE)
  utils::tar(
    tarfile = archive_file,
    files = c("effects.csv", "reproduce.R", "README.txt"),
    compression = "gzip",
    tar = "internal"
  )
  invisible(archive_file)
}

