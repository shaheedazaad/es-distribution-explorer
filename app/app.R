server <- function(input, output, session) {
  calculation <- reactiveVal(NULL)

  between_display <- reactive({
    result <- calculation()
    if (is.null(result)) {
      return(NULL)
    }
    transform_between_distribution(result$between, input$between_metric)
  })

  observeEvent(input$calculate, {
    selected <- filter_effects(
      effects,
      keyword = input$keyword,
      fields = input$field,
      conversion_bases = input$conversion_basis,
      preregistration = input$preregistration,
      year_range = input$year_range,
      journals = input$journal
    )

    withProgress(message = "Calculating weighted distributions", value = 0, {
      incProgress(0.1, detail = "Filtering effects")
      between <- prepare_effect_distribution(selected, "between")
      incProgress(0.45, detail = "Between-subjects distribution")
      within <- prepare_effect_distribution(selected, "within")
      incProgress(0.45, detail = "Within-subjects distribution")

      calculation(list(
        keyword = trimws(input$keyword),
        filters = list(
          keyword = trimws(input$keyword),
          fields = input$field,
          conversion_bases = input$conversion_basis,
          preregistration = input$preregistration,
          year_range = input$year_range,
          journals = input$journal
        ),
        filtered = selected,
        between = between,
        within = within
      ))
    })
  }, ignoreInit = TRUE)

  output$result_header <- renderUI({
    result <- calculation()
    if (is.null(result)) {
      return(tags$div(
        class = "results-intro",
        tags$div(
          tags$h2("No results calculated"),
          tags$p("Enter search terms or adjust filters, then click Calculate distributions.")
        )
      ))
    }

    search_label <- if (nzchar(result$keyword)) {
      paste0(" for “", result$keyword, "”")
    } else {
      ""
    }
    tags$div(
      class = "results-heading",
      tags$div(
        tags$p(class = "results-kicker", "RESULTS"),
        tags$h2(paste0(format(nrow(result$filtered), big.mark = ","),
          " matching effects", search_label))
      ),
      tags$div(
        class = "result-counts",
        tags$span(
          class = "count-chip chip-between",
          paste(format(result$between$usable_effects, big.mark = ","), "between")
        ),
        tags$span(
          class = "count-chip chip-within",
          paste(format(result$within$usable_effects, big.mark = ","), "within")
        )
      )
    )
  })

  output$between_plot <- renderPlot({
    specification <- between_metric_spec(input$between_metric)
    draw_effect_histogram(between_display(), "#2f6fa6", specification$x_label)
  }, res = 110)

  output$between_metric_description <- renderUI({
    tags$p(between_metric_spec(input$between_metric)$subtitle)
  })

  output$within_plot <- renderPlot({
    result <- calculation()
    distribution <- if (is.null(result)) NULL else result$within
    draw_effect_histogram(distribution, "#6a93b8", "Effect size (bias-corrected dz)")
  }, res = 110)

  output$between_quartiles <- renderUI({
    quartile_summary(between_display())
  })

  output$within_quartiles <- renderUI({
    result <- calculation()
    quartile_summary(if (is.null(result)) NULL else result$within)
  })

  output$reproduction_download_ui <- renderUI({
    if (is.null(calculation())) {
      return(NULL)
    }
    tags$div(
      class = "download-panel",
      tags$div(
        tags$strong("Reproduce this result"),
        tags$p(
          "Download the complete data and one standalone base-R script containing ",
          "the active search, filters, calculations, and plotting code."
        )
      ),
      shinylive_download_button(
        "download_reproduction",
        "Download reproduction package",
        class = "reproduction-button"
      )
    )
  })

  output$download_reproduction <- downloadHandler(
    filename = function() {
      paste0("effect-distribution-reproduction-", Sys.Date(), ".tar.gz")
    },
    contentType = "application/gzip",
    content = function(file) {
      result <- calculation()
      req(result)
      result$between_metric <- input$between_metric
      write_reproduction_package(result, file)
    }
  )
}

shinyApp(ui, server)
